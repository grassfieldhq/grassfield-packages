#!/usr/bin/env bash
# Make a bundled app's package canonical before anything signs, publishes or installs it (README.md, "Bundled apps"; third
# review of grassfield-packages PR #22).
#
#   app-repack.sh --app NAME --in PACKAGE --out DIR
#
# Why: the package file came out of a container that ran third-party code, and that code could write it. Every parser we
# write differs from libarchive's somewhere (Python's tarfile stops silently at a header libarchive accepts, a second
# .PKGINFO member is read by one reader and not by repo-add, a SIGPIPE inverts a grep), and pacman uses libarchive. So we do
# not predict what pacman will see: the signed artifact is rebuilt from a tree that libarchive itself extracted and that the
# filesystem itself describes, in the form makepkg's create_package gives.
#
# Runs in its own throwaway container with no network and nothing mounted but this repository (read-only), the package
# (read-only) and --out, as root (it refuses elsewhere; tests run it under fakeroot). Steps:
#   1. `bsdtar -tf` lists the members: no path twice (.PKGINFO included), every path one of the app's own (scripts/app-lib.sh).
#   2. bsdtar extracts it as root, never -P, into an empty folder, with --no-xattrs --no-acls --no-fflags: nothing in the
#      archive can put an attribute, a capability, an ACL or a flag on the tree.
#   3. The tree is checked on the filesystem, not with a parser: only regular files and folders; owner root:root; no setuid,
#      setgid or sticky bit and no group or world write; `getfattr -R -d -m -` prints nothing; only the allowed paths; the
#      binary and the .desktop file exist; one .PKGINFO and one .BUILDINFO (the filesystem keeps one).
#   4. Canonical form: folders 0755, files 0644 (the binary 0755), owner root, every mtime the package's builddate
#      (SOURCE_DATE_EPOCH), .MTREE regenerated by `bsdtar --format=mtree` with makepkg's options, the file list in makepkg's
#      order (list_package_files), `bsdtar --no-fflags -cnf` and zstd (one thread, so equal input gives equal bytes).
#   5. Proof: the new package is extracted again with xattrs, ACLs and flags ENABLED: no attribute appears and the tree is the
#      canonical one; then scripts/app-check.sh passes it.
# Only the file written to --out goes on (to the signer, repo-add and the desktop's container). Exit 0, 1 refused or
# failed (the reason on stderr), 2 usage.
set -euo pipefail
here=$(cd "$(dirname "$0")/.." && pwd)
app="" in="" out=""
usage() { echo "usage: app-repack.sh --app grassfield-sanaga|grassfield-notes --in PACKAGE --out DIR" >&2; exit 2; }
die() { echo "app-repack.sh: ${in##*/}: $*" >&2; exit 1; }
while (($#)); do
  [[ $# -ge 2 ]] || usage
  case $1 in --app) app=$2 ;; --in) in=$2 ;; --out) out=$2 ;; *) usage ;; esac
  shift 2
done
# shellcheck source=app-lib.sh
source "$here/scripts/app-lib.sh"
app_names "$app" || usage
[[ -f $in && ! -L $in && -d $out ]] || usage
[[ (-f /.dockerenv && $EUID == 0) || -n ${FAKEROOTKEY:-} ]] ||
  { echo "app-repack.sh: refused: runs only as root inside a throwaway container (tests: under fakeroot)" >&2; exit 2; }
av=$(bash -c 'source "$1/PKGBUILD" >/dev/null 2>&1; printf %s-%s "$pkgver" "$pkgrel"' _ "$here/$app")
file=$app-$av-x86_64.pkg.tar.zst
[[ ${in##*/} == "$file" ]] || die "the file is not named $file ($app/PKGBUILD's version)"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir "$work/tree" "$work/proof"

# 1. The members, as libarchive lists them.
list=$(bsdtar -tf "$in") || die "unreadable"
dups=$(printf '%s\n' "$list" | LC_ALL=C sort | uniq -d)
[[ -z $dups ]] || die "a path listed twice: $(head -n 1 <<<"$dups")"
while IFS= read -r p; do
  app_path_ok "$app" "$p" || die "a path that is not this app's: $p"
done <<<"$list"

# 1b. The owners and modes the archive records, as libarchive prints them: a second view of what the tree check below sees on the
# filesystem (root:root, no setuid, setgid or sticky bit, no group or world write), and the only one where a test runs as a user.
bad=$(bsdtar -tvf "$in" | awk '$1 !~ /^[-d][r-][w-][x-][r-]-[x-][r-]-[x-]$/ || $3 != "root" || $4 != "root" { print $1, $3, $4, $9 }' | head -n 1)
[[ -z $bad ]] || die "not a regular file or folder, not owned by root, a setuid, setgid or sticky bit, or a group- or world-writable mode: $bad"

# 2. Extracted by libarchive, with nothing but file data and the plain modes and owners.
owner=(--same-owner)
[[ -z ${FAKEROOTKEY:-} ]] || owner=(--no-same-owner)  # a test under fakeroot: a user cannot chown; step 1b has read the owners
bsdtar -xf "$in" -C "$work/tree" --no-xattrs --no-acls --no-fflags "${owner[@]}" -p || die "bsdtar cannot extract it"

# 3. The tree, on the filesystem itself.
cd "$work/tree"
[[ -z $(find . -mindepth 1 ! -type f ! -type d -print -quit) ]] || die "not only regular files and folders: $(find . -mindepth 1 ! -type f ! -type d -print -quit)"
# (Under fakeroot, a test, a user's files only look like root's through a preload that does not see every way bsdtar writes a
# file: there the owners are those step 1b read from the archive. As root in the container this is the filesystem's own answer.)
if [[ -z ${FAKEROOTKEY:-} ]]; then
  [[ -z $(find . \( ! -user root -o ! -group root \) -print -quit) ]] || die "not owned by root: $(find . \( ! -user root -o ! -group root \) -print -quit)"
fi
[[ -z $(find . -perm /7022 -print -quit) ]] || die "a setuid, setgid or sticky bit, or a group- or world-writable mode: $(find . -perm /7022 -print -quit)"
[[ -z $(getfattr -R -h -d -m - . 2>&1) ]] || die "extended attributes on the extracted tree"
while IFS= read -r -d '' p; do
  p=${p#./}
  [[ -d ./$p ]] && p+=/
  app_path_ok "$app" "$p" || die "a path that is not this app's: $p"
done < <(find . -mindepth 1 -print0)
[[ -f .PKGINFO && -f .BUILDINFO && -f usr/bin/$bin && -f usr/share/applications/$bin.desktop ]] || die "no .PKGINFO, .BUILDINFO, binary or .desktop file"
epoch=$(sed -n 's/^builddate = //p' .PKGINFO | head -n 1)
[[ $epoch =~ ^[0-9]{1,12}$ ]] || die ".PKGINFO has no numeric builddate"

# 4. The canonical form, as makepkg's create_package makes it.
rm -f .MTREE
find . -type d -exec chmod 0755 {} +
find . -type f -exec chmod 0644 {} +
chmod 0755 "usr/bin/$bin"
chown -R root:root . 2>/dev/null || [[ -n ${FAKEROOTKEY:-} ]] || die "cannot set the owner"
find . -exec touch -h -d "@$epoch" {} +
list_package_files() {
  (
    export LC_COLLATE=C
    shopt -s dotglob globstar
    printf '%s\0' **/*
  )
}
list_package_files | LANG=C bsdtar -cnf - --format=mtree --no-xattrs --no-acls \
  --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' --null --files-from - --exclude .MTREE | gzip -c -f -n >.MTREE
touch -d "@$epoch" .MTREE
list_package_files | LANG=C bsdtar --no-fflags --no-xattrs --no-acls --no-read-sparse -cnf - --null --files-from - |
  zstd -q -c -T1 -3 -- >"$work/$file"

# 5. The proof: extracted again with xattrs, ACLs and flags enabled, nothing appears; the tree is the canonical one.
cd "$work"
bsdtar -xf "$work/$file" -C "$work/proof" --xattrs --acls --fflags "${owner[@]}" -p || die "the repacked package does not extract"
[[ -z $(getfattr -R -h -d -m - "$work/proof" 2>&1) ]] || die "the repacked package carries extended attributes"
fmt='%p %y %m %u %g\n'
[[ -z ${FAKEROOTKEY:-} ]] || fmt='%p %y %m\n'
a=$(cd "$work/tree" && find . -mindepth 1 -printf "$fmt" | LC_ALL=C sort)
b=$(cd "$work/proof" && find . -mindepth 1 -printf "$fmt" | LC_ALL=C sort)
[[ $a == "$b" ]] || die "the repacked package extracts to another tree than the one checked"
[[ $(cd "$work/tree" && find . -type f -print0 | LC_ALL=C sort -z | xargs -0 sha256sum) == "$(cd "$work/proof" && find . -type f -print0 | LC_ALL=C sort -z | xargs -0 sha256sum)" ]] ||
  die "the repacked package has other file contents than the tree checked"
[[ $(bsdtar -tf "$work/$file" | LC_ALL=C sort -u | wc -l) == "$(bsdtar -tf "$work/$file" | wc -l)" ]] || die "the repacked package lists a path twice"
"$here/scripts/app-check.sh" "$work/$file" "$here/$app" || die "the repacked package fails app-check.sh"
install -m644 "$work/$file" "$out/$file"
echo "repacked $file $(sha256sum <"$out/$file" | cut -d' ' -f1)"
